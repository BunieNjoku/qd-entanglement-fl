"""
Module 6: Harvest-now / decrypt-later (HNDL) transcript experiment.

Turns the strongest security claim into a figure. Records
the FULL classical transcript of two-mask aggregation rounds in two arms
that differ ONLY in where pairwise masks come from, then grants a
recording adversary retroactive god-mode over every COMPUTATIONAL secret
(the standard model of a future cryptanalytically-relevant quantum
computer breaking DH / channel encryption / PRFs after the fact):

  classical arm - pairwise masks PRG-expanded from per-pair seeds that
      were established over recorded channels (Bonawitz: DH agreement;
      Flamingo: PRF seeds under channel encryption). God-mode recovers
      the seeds, recomputes every mask, and unmasks every recorded
      payload: expected retroactive gradient recovery 100%.

  entangled arm - pairwise masks sliced from source-model distilled
      pools. The shared bits are generated by local measurement at the
      endpoints and NEVER transit any channel; the transcript contains
      masked payloads, Shamir shares, self-mask seed disclosures, and
      the pairwise bits REVEALED for dropout recovery - nothing else.
      God-mode strips everything computational, but the never-
      transmitted pairwise bits are information-theoretically absent:
      every delivered payload retains >= 1 unrevealed pairwise mask,
      so expected retroactive recovery is 0% and residuals stay
      statistically uniform.

  it_dealer_online arm - pairwise masks are dealer-provisioned one-time
      pads with the SAME OTP mechanics as the entangled arm, but the
      dealer distributes each round's pads over recorded classical
      channels under computational encryption.
      God-mode decrypts the recorded pad ciphertexts, so every pairwise
      pad is in the transcript: expected retroactive gradient recovery
      100%. IT-secure MASKING with computationally-secured PROVISIONING
      is still HNDL-exposed - the hole moves one layer down.

  it_dealer_courier arm - the same dealer pads delivered out of band
      (courier / HSM install). No pad ever crosses a recorded channel,
      so the transcript is byte-identical in shape to the entangled
      arm's and the attack has nothing to open: expected retroactive
      recovery 0%. The two dealer arms differ ONLY in provisioning,
      which is what makes HNDL immunity a provisioning property in
      the data rather than in the argument. The courier arm's immunity
      is against a CHANNEL recorder only; the dealer generated and
      held every pad, and future pads sit in storage between visits.

The t >= 2 structural argument, stated once: a payload loses ALL its
pairwise masks only if every partner's pairwise material is revealed,
i.e. all other cluster members dropped - but then survivors < Shamir
threshold, the cluster ABORTS at the live-set announcement, and the
payload is never transmitted (see RoundComm in m4). Delivered payloads
therefore always keep at least one unrevealed mask.

Honest scope (applies to ALL arms here): the
self-mask leg rides classical channels via Shamir shares and is only
computationally protected - god-mode strips every self-mask in this
experiment. The pairwise leg ALONE carries the HNDL claim. EC syndromes
(~0.20 bits/secret bit) also appear in the recorded transcript; the
masks are sliced from post-PA output, which the Leftover Hash Lemma
makes ε-close to uniform GIVEN the syndrome leakage - recorded
syndromes do not help the adversary beyond the ε accounted in PA.

Every wire object here is produced by the SAME primitives as the live
protocol (quantize_gradient, derive_modular_mask, apply_modular_mask,
shamir_split/reconstruct, the same PRG self-mask expansion), and the
experiment asserts its aggregate equals secure_aggregation_round's on
identical inputs - the transcript cannot silently diverge from the
implementation it indicts/exonerates.
"""
import numpy as np
from dataclasses import dataclass, field
from typing import Dict, List, Set, Tuple

try:
    from modules.m4_federated_learning import (
        quantize_gradient, dequantize_gradient, derive_modular_mask,
        apply_modular_mask, shamir_split, shamir_reconstruct,
        _SHAMIR_PRIME, QUANT_SCALE,
    )
    from modules.m2_post_processing import nist_monobit
except ImportError:  # pragma: no cover - package-relative fallback
    from .m4_federated_learning import (
        quantize_gradient, dequantize_gradient, derive_modular_mask,
        apply_modular_mask, shamir_split, shamir_reconstruct,
        _SHAMIR_PRIME, QUANT_SCALE,
    )
    from .m2_post_processing import nist_monobit


def _prg_mask(seed, n_params):
    """The protocol's PRG expansion (identical to m4's self-mask path)."""
    return (np.random.default_rng(int(seed))
            .integers(0, 1 << 32, size=n_params, dtype=np.uint64)
            .astype(np.uint32))


@dataclass
class TranscriptRound:
    """Everything a recording adversary captured for one cluster round,
    PLUS ground truth (held separately, never part of the transcript)."""
    round_idx: int
    cluster: List[int]
    dropouts: Set[int]
    # --- recorded wire objects (the transcript proper) ---
    masked_payloads: Dict[int, np.ndarray]          # survivors only
    seed_shares: Dict[int, list]                     # Shamir shares in flight
    disclosed_seeds: Dict[int, int]                  # survivors' self-mask seeds
    revealed_pair_bits: Dict[Tuple[int, int], np.ndarray]  # dropout reveals
    # classical arm only: the per-pair mask seeds become god-mode-readable
    # (DH-derivable / decryptable after the fact). None in the entangled arm.
    pair_mask_seeds: Dict[Tuple[int, int], int] = None
    # it_dealer_online arm only: the dealer's per-round pad distribution,
    # recorded as TLS ciphertexts on the wire; god-mode decrypts them.
    # None in the other arms (the courier arm's pads never touch a
    # recorded channel).
    dealer_pad_bits: Dict[Tuple[int, int], np.ndarray] = None
    # Dealer arms only (online AND courier): the provisioning party's OWN
    # archive of every pad it generated. NOT part of the transcript - the
    # recorder never sees it; it is consumed only by the second adversary
    # (retroactive_attack with provisioner_compromise=True), which models
    # compromise or subpoena of the dealer itself. None in the classical
    # and entangled arms: no third party holds their key material.
    provisioner_pad_bits: Dict[Tuple[int, int], np.ndarray] = None
    # --- ground truth for scoring (NOT in the transcript) ---
    truth_quant: Dict[int, np.ndarray] = field(default_factory=dict)


# Arms whose pairwise masks are one-time pads sliced from a pool (the
# classical arm PRG-expands seeds instead).
_POOL_ARMS = ("entangled", "it_dealer_online", "it_dealer_courier")


def run_transcript_round(round_idx, gradients, cluster, dropouts, arm,
                         pairwise_pool=None, pair_mask_seeds=None,
                         self_seeds=None):
    """One two-mask round, wire-faithful, recording the full transcript.

    arm='entangled': pairwise masks from `pairwise_pool` (distilled bits,
    3 x n_params x 32 for a triangle), exactly like secure_aggregation_round.
    arm='classical': pairwise masks PRG-expanded from `pair_mask_seeds`
    (the Bonawitz/Flamingo shape - seeds established over recorded
    channels).
    arm='it_dealer_online': pairwise masks are dealer-provisioned pads
    (from `pairwise_pool`, same OTP mechanics as the entangled arm), but
    the dealer's pad-distribution messages ride recorded classical
    channels under computational encryption - so the pads themselves
    join the transcript as ciphertexts god-mode can open later.
    arm='it_dealer_courier': the same pads delivered out of band; the
    transcript carries no provisioning messages at all.

    Returns (TranscriptRound, aggregate_quantized) where the aggregate is
    the unmasked modular sum of survivor payloads (for the coherence
    assertion against secure_aggregation_round).
    """
    cluster = list(cluster)
    dropouts = set(dropouts)
    survivors = [c for c in cluster if c not in dropouts]
    n_params = gradients[cluster[0]].numel()
    bits_per_mask = n_params * 32

    quant = {c: quantize_gradient(gradients[c]) for c in cluster}

    # Pairwise masks - same iteration order and canonical (min,max) keying
    # as secure_aggregation_round step 2.
    pair_masks = {}
    pair_bits = {}
    off = 0
    for i_idx, ci in enumerate(cluster):
        for cj in cluster[i_idx + 1:]:
            key = (ci, cj)
            if arm in _POOL_ARMS:
                bits = pairwise_pool[off:off + bits_per_mask]
                off += bits_per_mask
                pair_masks[key] = derive_modular_mask(n_params, bits)
                pair_bits[key] = bits
            else:
                pair_masks[key] = _prg_mask(pair_mask_seeds[key], n_params)
    # Self-masks + Shamir shares - same expansion as m4 step 3.
    self_masks, shares = {}, {}
    for c in cluster:
        seed = int(self_seeds[c]) % _SHAMIR_PRIME
        self_masks[c] = _prg_mask(seed, n_params)
        shares[c] = shamir_split(seed, len(cluster), 2,
                                 np.random.default_rng(seed + 1))

    # Payloads - m4 step 4, survivors only (pre-payload drop timing).
    payloads = {}
    for c in survivors:
        p = quant[c].copy()
        for c2 in cluster:
            if c2 == c:
                continue
            lo, hi = (c, c2) if c < c2 else (c2, c)
            p = apply_modular_mask(p, pair_masks[(lo, hi)],
                                   sign=+1 if c < c2 else -1)
        p = apply_modular_mask(p, self_masks[c], sign=+1)
        payloads[c] = p

    # Dropout reveals - each survivor reveals its pairwise BITS with each
    # dropped partner (m4 step 6). In the classical arm the analogous
    # reveal is the pair PRF seed; recording either suffices for god-mode,
    # so we record the reconstructed mask source in both arms.
    revealed = {}
    for c in dropouts:
        for s in survivors:
            lo, hi = (s, c) if s < c else (c, s)
            if arm in _POOL_ARMS:
                revealed[(lo, hi)] = pair_bits[(lo, hi)]
            else:
                revealed[(lo, hi)] = np.int64(pair_mask_seeds[(lo, hi)])

    # Aggregator unmask (for the coherence check): sum payloads, remove
    # surviving self-masks, neutralize dropped clients' pairwise residues.
    agg = np.zeros(n_params, dtype=np.uint32)
    for c, p in payloads.items():
        agg = (agg + p).astype(np.uint32)
    for c in survivors:
        agg = (agg - self_masks[c]).astype(np.uint32)
    for c in dropouts:
        for s in survivors:
            lo, hi = (s, c) if s < c else (c, s)
            resid = pair_masks[(lo, hi)]
            agg = ((agg - resid) if s < c else (agg + resid)).astype(np.uint32)

    tr = TranscriptRound(
        round_idx=round_idx, cluster=cluster, dropouts=dropouts,
        masked_payloads=payloads, seed_shares=shares,
        disclosed_seeds={c: int(self_seeds[c]) % _SHAMIR_PRIME
                         for c in survivors},
        revealed_pair_bits=revealed,
        pair_mask_seeds=dict(pair_mask_seeds) if arm == "classical" else None,
        # The dealer's per-round pad distribution is ON THE WIRE (under
        # computational encryption) - the recorder keeps the ciphertexts.
        dealer_pad_bits=(dict(pair_bits) if arm == "it_dealer_online"
                         else None),
        # Whatever the delivery channel, the DEALER generated these pads
        # and can retain them: its archive exists in both dealer arms.
        provisioner_pad_bits=(dict(pair_bits)
                              if arm in ("it_dealer_online",
                                         "it_dealer_courier") else None),
        truth_quant=quant,
    )
    return tr, agg


def retroactive_attack(transcript: List[TranscriptRound], arm,
                       provisioner_compromise=False):
    """Replay the recorded transcript with god-mode over computational
    secrets; attempt to unmask every recorded payload.

    God-mode grants (all arms): channel encryption broken -> Shamir
    shares readable -> every self-mask seed reconstructible (the
    computationally-protected leg falls, as documented); all dropout
    reveals readable. Classical arm additionally: per-pair mask seeds
    (DH/PRF) broken -> every pairwise mask recomputable. Online-dealer
    arm additionally: recorded pad ciphertexts opened. The courier-
    dealer and entangled arms grant nothing further - there is nothing
    further in their transcripts.

    provisioner_compromise=True adds the second adversary: the recorder
    ALSO obtains the provisioning party's own key archive (dealer
    compromise or subpoena). This hands over provisioner_pad_bits where
    a provisioning third party exists (both dealer arms) and nothing
    where none does (classical: keys negotiated pairwise; entangled:
    keys distilled pairwise) - so the same adversary runs against every
    arm and the difference in outcome is the arm's trust structure.

    Returns per-payload records and summary fractions.
    """
    records = []
    for tr in transcript:
        n_params = next(iter(tr.truth_quant.values())).shape[0]
        # God-mode self-masks: reconstruct each owner's seed from any 2
        # recorded shares (threshold=2), PRG-expand - same primitives.
        selfmask = {}
        for owner, sh in tr.seed_shares.items():
            seed = shamir_reconstruct(sh[:2])
            selfmask[owner] = _prg_mask(seed, n_params)
            if owner in tr.disclosed_seeds:
                assert seed == tr.disclosed_seeds[owner], \
                    "share-derived seed != disclosed seed (transcript bug)"
        for c, payload in tr.masked_payloads.items():
            residual = (payload - selfmask[c]).astype(np.uint32)
            stripped = 0
            unstripped_pairs = []
            for c2 in tr.cluster:
                if c2 == c:
                    continue
                lo, hi = (c, c2) if c < c2 else (c2, c)
                sign = +1 if c < c2 else -1
                mask = None
                if arm == "classical":
                    mask = _prg_mask(tr.pair_mask_seeds[(lo, hi)], n_params)
                elif arm == "it_dealer_online":
                    # God-mode decrypts the recorded pad ciphertexts:
                    # every pairwise pad is in the transcript.
                    mask = derive_modular_mask(
                        n_params, tr.dealer_pad_bits[(lo, hi)])
                elif (provisioner_compromise
                      and tr.provisioner_pad_bits is not None
                      and (lo, hi) in tr.provisioner_pad_bits):
                    # Second adversary: the dealer's own archive.
                    mask = derive_modular_mask(
                        n_params, tr.provisioner_pad_bits[(lo, hi)])
                elif (lo, hi) in tr.revealed_pair_bits:
                    mask = derive_modular_mask(
                        n_params, tr.revealed_pair_bits[(lo, hi)])
                if mask is not None:
                    residual = apply_modular_mask(residual, mask, sign=-sign)
                    stripped += 1
                else:
                    unstripped_pairs.append((lo, hi))
            truth = tr.truth_quant[c]
            exact = bool(np.array_equal(residual, truth))
            # Residual statistics. VALIDATION ONLY on the entangled
            # arms: a residual carrying an unstripped one-time pad is
            # uniform by theorem, so a PASS confirms nothing and a FAIL
            # means a mask reached the transcript - an implementation
            # bug. The test discriminates only on the classical arms,
            # where god-mode strips everything and the residual is the
            # gradient itself. The reported finding is the recovered
            # fraction, not this p-value.
            res_bits = np.unpackbits(
                residual[:4096].view(np.uint8)).astype(np.int8)
            err = np.abs(dequantize_gradient(residual).numpy()
                         - dequantize_gradient(truth).numpy())
            records.append({
                "round": tr.round_idx, "client": c,
                "masks_stripped": stripped,
                "masks_remaining": len(unstripped_pairs),
                "exact_recovery": exact,
                "residual_monobit_p": nist_monobit(res_bits),
                "median_abs_error": float(np.median(err)),
            })
    n = len(records)
    return {
        "records": records,
        "n_payloads": n,
        "recovered_fraction": sum(r["exact_recovery"] for r in records) / n,
        "min_masks_remaining": min(r["masks_remaining"] for r in records),
        "mean_residual_monobit_p": float(np.mean(
            [r["residual_monobit_p"] for r in records])),
        "median_abs_error": float(np.median(
            [r["median_abs_error"] for r in records])),
    }
